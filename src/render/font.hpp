// Find a glyph's 7 string rows (blank for unknown characters).
inline const char* const* fontGlyphRows(char c) {
    static const char* kBlank[7] = {".....", ".....", ".....", ".....", ".....", ".....", "....."};
    int n = 0;
    const FontGlyph* g = fontGlyphs(n);
    char up = (c >= 'a' && c <= 'z') ? char(c - 'a' + 'A') : c;
    for (int i = 0; i < n; ++i)
        if (g[i].ch == up) return g[i].rows;
    return kBlank;
}

// RGBA atlas: ASCII 0..127 in a 16x8 grid of 8x8 cells (128x64 px). Glyph ink
// is white with full alpha; callers tint via the text color uniform.
struct FontAtlas {
    static constexpr int kCell = 8, kCols = 16, kRows = 8;
    static constexpr int kW = kCols * kCell;   // 128
    static constexpr int kH = kRows * kCell;   // 64
    uint8_t px[kW * kH * 4]{};
};

inline const FontAtlas& fontAtlas() {
    static FontAtlas a{};
    static bool built = false;
    if (!built) {
        built = true;
        for (int c = 0; c < 128; ++c) {
            const char* const* rows = fontGlyphRows(char(c));
            int col = c % FontAtlas::kCols, row = c / FontAtlas::kCols;
            for (int gy = 0; gy < 7; ++gy) {
                for (int gx = 0; gx < 5; ++gx) {
                    if (rows[gy][gx] != '#') continue;
                    int x = col * FontAtlas::kCell + 1 + gx;
                    int y = row * FontAtlas::kCell + gy;
                    uint8_t* p = &a.px[(y * FontAtlas::kW + x) * 4];
                    p[0] = p[1] = p[2] = p[3] = 255;
                }
            }
        }
    }
    return a;
}

// Text metrics (pixels): 6px advance, 8px line height, times scale.
inline int textWidthPx(const char* s, int scale) {
    return int(std::strlen(s)) * 6 * scale;
}
inline int textHeightPx(int scale) { return 8 * scale; }

